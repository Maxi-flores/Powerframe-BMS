import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);

const DEFAULTS = {
  breakpoints: {
    sm: "600px",
    md: "900px",
    lg: "1200px",
    xl: "1536px",
  },
  spacing: {
    0: "0px",
    1: "4px",
    2: "8px",
    3: "12px",
    4: "16px",
    5: "20px",
    6: "24px",
    8: "32px",
    10: "40px",
    12: "48px",
    16: "64px",
  },
  containers: {
    sm: "640px",
    md: "768px",
    lg: "1024px",
    xl: "1280px",
  },
};

function isPlainObject(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function normalizeCssSize(value) {
  if (value == null) return null;
  if (typeof value === "number" && Number.isFinite(value)) return `${value}px`;
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  if (!trimmed) return null;
  if (/^-?\d+(\.\d+)?$/.test(trimmed)) return `${trimmed}px`;
  if (/^-?\d+(\.\d+)?(px|rem|em|vw|vh|vmin|vmax|%)$/.test(trimmed)) return trimmed;
  return trimmed;
}

function asTokenValue(value) {
  if (isPlainObject(value) && typeof value.value === "string") return value.value;
  if (isPlainObject(value) && typeof value.value === "number") return value.value;
  return value;
}

function pickFirst(obj, candidates) {
  for (const candidate of candidates) {
    if (!candidate) continue;
    const value = obj?.[candidate];
    if (value != null) return value;
  }
  return null;
}

function deepGet(obj, pathParts) {
  let current = obj;
  for (const part of pathParts) {
    if (!isPlainObject(current)) return null;
    current = current[part];
    if (current == null) return null;
  }
  return current;
}

function findFirstSection(tokens, sectionNames) {
  for (const name of sectionNames) {
    const direct = tokens?.[name];
    if (direct != null) return direct;
    const nested = deepGet(tokens, ["global", name]);
    if (nested != null) return nested;
    const core = deepGet(tokens, ["core", name]);
    if (core != null) return core;
  }
  return null;
}

function extractBreakpoints(tokens) {
  const raw =
    findFirstSection(tokens, ["breakpoints", "breakpoint", "screens"]) ??
    null;

  const result = { ...DEFAULTS.breakpoints };
  if (!isPlainObject(raw)) return result;

  for (const key of Object.keys(result)) {
    const candidate = raw[key] ?? raw[key.toUpperCase()];
    const normalized = normalizeCssSize(asTokenValue(candidate));
    if (normalized) result[key] = normalized;
  }

  return result;
}

function extractContainers(tokens) {
  const raw = findFirstSection(tokens, ["containers", "container", "layout"]) ?? null;

  const result = { ...DEFAULTS.containers };
  if (!isPlainObject(raw)) return result;

  const containerSection =
    pickFirst(raw, ["maxWidth", "maxWidths", "sizes", "container"]) ?? raw;

  if (!isPlainObject(containerSection)) return result;

  for (const key of Object.keys(result)) {
    const candidate = containerSection[key] ?? containerSection[key.toUpperCase()];
    const normalized = normalizeCssSize(asTokenValue(candidate));
    if (normalized) result[key] = normalized;
  }

  return result;
}

function extractSpacing(tokens) {
  const raw = findFirstSection(tokens, ["spacing", "space"]) ?? null;
  const result = { ...DEFAULTS.spacing };
  if (!isPlainObject(raw)) return result;

  for (const [key, value] of Object.entries(raw)) {
    if (!/^\d+$/.test(String(key))) continue;
    const normalized = normalizeCssSize(asTokenValue(value));
    if (normalized) result[key] = normalized;
  }

  return result;
}

function sortNumericKeys(obj) {
  return Object.fromEntries(
    Object.entries(obj).sort(([a], [b]) => Number(a) - Number(b)),
  );
}

function buildCss({ breakpoints, spacing, containers }) {
  const spacingSorted = sortNumericKeys(spacing);
  const containerMax = containers.xl || containers.lg || DEFAULTS.containers.xl;

  const lines = [];
  lines.push("/* AUTO-GENERATED FILE. DO NOT EDIT BY HAND. */");
  lines.push("/* Generated by: apps/gms/scripts/sync-layout-tokens.js */");
  lines.push("");
  lines.push(":root {");

  lines.push(`  --gms-bp-sm: ${breakpoints.sm};`);
  lines.push(`  --gms-bp-md: ${breakpoints.md};`);
  lines.push(`  --gms-bp-lg: ${breakpoints.lg};`);
  lines.push(`  --gms-bp-xl: ${breakpoints.xl};`);
  lines.push("");

  lines.push(`  --gms-container-sm: ${containers.sm};`);
  lines.push(`  --gms-container-md: ${containers.md};`);
  lines.push(`  --gms-container-lg: ${containers.lg};`);
  lines.push(`  --gms-container-xl: ${containers.xl};`);
  lines.push(`  --gms-container-max: ${containerMax};`);
  lines.push("");

  for (const [k, v] of Object.entries(spacingSorted)) {
    lines.push(`  --gms-spacing-${k}: ${v};`);
  }

  lines.push("");
  lines.push("  /* Structural layout knobs (consumed by legacy CSS + primitives) */");
  lines.push("  --gms-shell-padding: 18px;");
  lines.push("  --gms-shell-gap: 18px;");
  lines.push("  --gms-topbar-radius: 20px;");
  lines.push("  --gms-topbar-padding-x: 14px;");
  lines.push("  --gms-topbar-left-min: 240px;");

  lines.push("}");
  lines.push("");

  lines.push("/* Responsive structural overrides (literal media queries) */");
  lines.push(`@media (max-width: ${breakpoints.md}) {`);
  lines.push("  :root {");
  lines.push("    --gms-topbar-left-min: auto;");
  lines.push("  }");
  lines.push("}");
  lines.push("");

  lines.push(`@media (max-width: ${breakpoints.sm}) {`);
  lines.push("  :root {");
  lines.push("    --gms-shell-padding: 10px;");
  lines.push("    --gms-shell-gap: 10px;");
  lines.push("    --gms-topbar-radius: 14px;");
  lines.push("    --gms-topbar-padding-x: 10px;");
  lines.push("  }");
  lines.push("}");
  lines.push("");

  lines.push("/* Responsive helpers */");
  lines.push(`@media (max-width: ${breakpoints.md}) { .gms-hide-below-md { display: none !important; } }`);
  lines.push(`@media (max-width: ${breakpoints.sm}) { .gms-hide-below-sm { display: none !important; } }`);
  lines.push("");

  return `${lines.join("\n")}\n`;
}

async function loadTokensJson() {
  try {
    const tokensPath = require.resolve("@trt/tokens/tokens.json");
    const raw = await fs.readFile(tokensPath, "utf8");
    return JSON.parse(raw);
  } catch (err) {
    const msg = err?.message || String(err);
    return { __loadError: String(msg).split("\n")[0] };
  }
}

async function writeFileIfChanged(filePath, contents) {
  let existing = null;
  try {
    existing = await fs.readFile(filePath, "utf8");
  } catch {
    existing = null;
  }

  if (existing === contents) return false;

  await fs.mkdir(path.dirname(filePath), { recursive: true });
  const tmpPath = `${filePath}.tmp`;
  await fs.writeFile(tmpPath, contents, "utf8");
  await fs.rename(tmpPath, filePath);
  return true;
}

async function main() {
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const outPath = path.resolve(scriptDir, "..", "src", "styles", "layout-tokens.css");

  const tokens = await loadTokensJson();
  const hadLoadError = Boolean(tokens?.__loadError);

  const breakpoints = extractBreakpoints(tokens);
  const spacing = extractSpacing(tokens);
  const containers = extractContainers(tokens);

  const css = buildCss({ breakpoints, spacing, containers });
  const changed = await writeFileIfChanged(outPath, css);

  const statusParts = [];
  statusParts.push(changed ? "updated" : "unchanged");
  statusParts.push(path.relative(process.cwd(), outPath));

  if (hadLoadError) {
    statusParts.push("(using defaults; failed to load @trt/tokens)");
    process.stderr.write(`sync-layout-tokens: warn: ${tokens.__loadError}\n`);
  }

  process.stdout.write(`sync-layout-tokens: ${statusParts.join(" ")}\n`);
}

main().catch((err) => {
  process.stderr.write(`sync-layout-tokens: fatal: ${err?.stack || err}\n`);
  process.exitCode = 1;
});
